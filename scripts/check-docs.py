#!/usr/bin/env python3
"""Validate RAVET's live documentation; --write regenerates the feature catalogue.

Python 3.11+; standard library only. Does not require Git history or a remote.
"""

import argparse
import pathlib
import re
import sys
import tomllib
from urllib.parse import unquote, urlsplit

ROOT = pathlib.Path(__file__).resolve().parents[1]
STATUSES = {
    "implemented": "Implemented",
    "prototype": "Prototype",
    "planned": "Planned",
    "deferred": "Deferred",
    "excluded": "Excluded",
}
FIELDS = {"id", "title", "status", "summary", "limits", "sources", "tests", "docs"}


def read_toml(path):
    return tomllib.loads(path.read_text(encoding="utf-8"))


def evidence_path(root, value):
    """Require durable, relative file references within the repository."""
    path = pathlib.PurePosixPath(value)
    if path.is_absolute() or ".." in path.parts or "target" in path.parts:
        raise ValueError(f"invalid repository evidence path: {value}")
    resolved = (root / path).resolve()
    if not resolved.is_relative_to(root.resolve()) or not resolved.is_file():
        raise ValueError(f"missing or invalid evidence file: {value}")
    return resolved


def load_catalogue(root):
    registry = read_toml(root / "docs/features.toml")
    if registry.get("schema_version") != 1 or set(registry) != {"schema_version", "feature"}:
        raise ValueError("docs/features.toml: expected schema_version = 1 and feature records")
    features = registry["feature"]
    if not isinstance(features, list) or not features:
        raise ValueError("docs/features.toml: feature records must be a nonempty list")
    ids = set()
    sources = set()
    for feature in features:
        if not isinstance(feature, dict) or set(feature) != FIELDS:
            raise ValueError(f"feature record must contain exactly: {', '.join(sorted(FIELDS))}")
        for key in ("id", "title", "status", "summary", "limits"):
            if not isinstance(feature[key], str) or not feature[key].strip() or "\n" in feature[key]:
                raise ValueError(f"feature {key} must be a nonempty single-line string")
        feature_id = feature["id"]
        if not re.fullmatch(r"[a-z][a-z0-9]*(?:-[a-z0-9]+)*", feature_id):
            raise ValueError(f"invalid feature ID: {feature_id}")
        if feature_id in ids:
            raise ValueError(f"duplicate feature ID: {feature_id}")
        ids.add(feature_id)
        if feature["status"] not in STATUSES:
            raise ValueError(f"{feature_id}: unknown status {feature['status']!r}")
        for key in ("sources", "tests", "docs"):
            values = feature[key]
            if not isinstance(values, list) or any(not isinstance(v, str) or not v for v in values):
                raise ValueError(f"{feature_id}: {key} must be a list of file paths")
            if len(values) != len(set(values)):
                raise ValueError(f"{feature_id}: duplicate {key} paths")
            for value in values:
                evidence_path(root, value)
        if not feature["docs"]:
            raise ValueError(f"{feature_id}: at least one documentation reference is required")
        if feature["status"] in ("implemented", "prototype"):
            if not feature["sources"] or not feature["tests"]:
                raise ValueError(f"{feature_id}: working features require source and test evidence")
        sources.update(feature["sources"])

    workspace = read_toml(root / "Cargo.toml")["workspace"]
    members = set()
    for pattern in workspace["members"]:
        matches = {p for p in root.glob(pattern) if (p / "Cargo.toml").is_file()}
        if not matches:
            raise ValueError(f"workspace member has no Cargo manifest: {pattern}")
        members.update(matches)
    excluded = {p for pattern in workspace.get("exclude", []) for p in root.glob(pattern)}
    packages = []
    for member in members - excluded:
        manifest = member / "Cargo.toml"
        package = read_toml(manifest)["package"]
        relative = member.relative_to(root).as_posix()
        if not any(p.startswith(relative + "/") for p in sources):
            raise ValueError(f"workspace package lacks a feature source reference: {relative}")
        description = package.get("description")
        if not isinstance(description, str) or not description.strip():
            raise ValueError(f"{relative}/Cargo.toml: package description is required")
        packages.append((package["name"], description, f"{relative}/Cargo.toml"))
    return features, sorted(packages)


def table_text(value):
    return value.replace("|", "\\|").replace("\n", " ")


def file_link(path):
    # Catalogue lives one directory below the repository root.
    return f"[`{path}`](../{path})"


def render_catalogue(features, packages):
    lines = [
        "<!-- Generated by scripts/check-docs.py from docs/features.toml and Cargo manifests. -->",
        "<!-- Do not edit directly. Run: python3 scripts/check-docs.py --write -->",
        "# RAVET feature catalogue",
        "",
        "Current capabilities and their limits. Implemented features remain within",
        "the stated scope; public APIs are provisional. Prototype integrations need",
        "further validation. Planned and deferred capabilities are not usable features.",
        "",
        "See [Getting started](getting-started.md) for commands,",
        "[work status](WORK_STATUS.md) for executed validation, and",
        "[maintenance](maintenance.md) for status definitions and update rules.",
        "",
        "## Feature overview",
        "",
        "| Feature | Status | Behavior or intent |",
        "|---|---|---|",
    ]
    for feature in features:
        lines.append(
            f"| [{table_text(feature['title'])}](#{feature['id']}) "
            f"| {STATUSES[feature['status']]} | {table_text(feature['summary'])} |"
        )
    for status, label in STATUSES.items():
        matching = [f for f in features if f["status"] == status]
        if not matching:
            continue
        lines.extend(["", f"## {label} capabilities"])
        for feature in matching:
            lines.extend([
                "",
                f"<a id=\"{feature['id']}\"></a>",
                "",
                f"### {feature['title']}",
                "",
                feature["summary"],
                "",
                f"**Limits:** {feature['limits']}",
            ])
            for key, name in (("sources", "Source"), ("tests", "Tests"), ("docs", "Documentation")):
                if feature[key]:
                    lines.extend(["", f"**{name}:** " + ", ".join(file_link(p) for p in feature[key]) + "."])
    lines.extend([
        "",
        "## Workspace packages",
        "",
        "Generated from workspace member manifests. Descriptions identify package",
        "roles; feature records above determine implementation status.",
        "",
        "| Package | Description | Manifest |",
        "|---|---|---|",
    ])
    for name, description, manifest in packages:
        lines.append(f"| `{table_text(name)}` | {table_text(description)} | {file_link(manifest)} |")
    return "\n".join(lines) + "\n"


def prose_only(text):
    """Ignore example code, including unmatched fences while drafting."""
    lines = []
    fence = None
    for line in text.splitlines():
        marker = re.match(r"^\s{0,3}(`{3,}|~{3,})", line)
        if marker:
            token = marker[1]
            if fence is None:
                fence = token
            elif token[0] == fence[0] and len(token) >= len(fence):
                fence = None
            continue
        if fence is None:
            # Preserve Markdown links whose visible label is inline code.
            lines.append(re.sub(r"(`+).*?\1", "", line))
    return re.sub(r"<!--.*?-->", "", "\n".join(lines), flags=re.DOTALL)


def check_links(root):
    """Check inline local Markdown file/directory destinations, not anchors/URLs."""
    errors = []
    documents = sorted(set(root.glob("*.md")) | set((root / "docs").rglob("*.md")))
    link_pattern = re.compile(r"!?\[[^\]\n]*\]\(\s*(<[^>\n]+>|[^\s)]+)(?:\s+[^)]+)?\)")
    for document in documents:
        content = prose_only(document.read_text(encoding="utf-8"))
        for match in link_pattern.finditer(content):
            destination = match[1].strip("<>")
            parsed = urlsplit(destination)
            if parsed.scheme or parsed.netloc or not parsed.path:
                continue
            path = (document.parent / unquote(parsed.path)).resolve()
            if not path.is_relative_to(root.resolve()) or not path.exists():
                errors.append(f"{document.relative_to(root)}: broken local link {destination}")
    return errors


def check(root, write=False):
    features, packages = load_catalogue(root)
    output = render_catalogue(features, packages)
    target = root / "docs/FEATURES.md"
    if write:
        target.write_text(output, encoding="utf-8")
    errors = []
    if not target.is_file() or target.read_text(encoding="utf-8") != output:
        errors.append("docs/FEATURES.md is stale; run python3 scripts/check-docs.py --write")
    errors.extend(check_links(root))
    return errors


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--write", action="store_true", help="regenerate docs/FEATURES.md before checking")
    args = parser.parse_args()
    try:
        errors = check(ROOT, args.write)
    except (ValueError, KeyError, TypeError, OSError) as error:
        errors = [str(error)]
    if errors:
        print("Documentation check failed:", file=sys.stderr)
        for error in errors:
            print(f"- {error}", file=sys.stderr)
        return 1
    print("Documentation check passed: catalogue, evidence, package coverage, and local links.")
    return 0


if __name__ == "__main__":
    sys.exit(main())
